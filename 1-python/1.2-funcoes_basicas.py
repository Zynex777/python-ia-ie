# Entrada e saída: input() lê texto, int() converte a idade e print() exibe os dados.
# As variáveis guardam valores para reutilização nas instruções seguintes.

#criando as variaveis
nome = input("Digite seu nome: ")
idade = int(input("Digite sua idade: "))

#apresentando os dados do usuario
print(nome,"possui idade de",idade,"anos.")