def somar (item1, item2):
    resultado = item1 + item2
    return resultado
def subtrair (item1, item2):
    resultado = item1 - item2
    return resultado
def multiplicar (item1, item2):
    resultado = item1 * item2
    return resultado
def dividir (item1, item2):
    resultado = item1 / item2
    return resultado